    public function execute( array $arguments ) {
        $this->validate_required( $arguments, array( 'post_id', 'ops' ) );

        $post_id   = $this->parse_required_id( $arguments['post_id'], 'post_id' );
        $post_type = ! empty( $arguments['post_type'] )
            ? $this->validate_rest_route_segment( $arguments['post_type'], 'post_type' )
            : 'posts';
        $dry_run   = ! empty( $arguments['dry_run'] ) && rest_sanitize_boolean( $arguments['dry_run'] );

        $ops = $this->parse_json_param( $arguments['ops'], 'ops' );
        if ( array() === $ops || array_keys( $ops ) !== range( 0, count( $ops ) - 1 ) ) {
            throw new \InvalidArgumentException( 'ops must be a non-empty array of operation objects.' );
        }

        
        $data = $this->rest_request( 'GET', '/wp/v2/' . $post_type . '/' . $post_id, array( 'context' => 'edit' ) );
        if ( ! isset( $data['content']['raw'] ) ) {
            throw new \RuntimeException( 'The post content could not be read in edit context.' );
        }

        $root = array(
            'blockName'    => null,
            'attrs'        => array(),
            'innerBlocks'  => parse_blocks( (string) $data['content']['raw'] ),
            'innerHTML'    => '',
            'innerContent' => null,
        );

        $warnings = array();
        $changes  = array();
        foreach ( $ops as $i => $op ) {
            if ( ! is_array( $op ) ) {
                throw new \InvalidArgumentException( sprintf( 'ops[%d] must be an object.', $i ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            }
            $changes[] = $this->apply_op( $root, $op, (int) $i, $warnings );
        }

        $content     = serialize_blocks( $root['innerBlocks'] );
        $block_count = count( $this->addressable_indexes( $root['innerBlocks'] ) );

        $result = array(
            'post_id'     => $post_id,
            'saved'       => false,
            'ops_applied' => count( $changes ),
            'block_count' => $block_count,
            'warnings'    => $warnings,
            'changes'     => $changes,
        );

        if ( $dry_run ) {
            $result['dry_run'] = true;
            return $result;
        }

        
        
        
        $saved = $this->rest_request( 'POST', '/wp/v2/' . $post_type . '/' . $post_id, array( 'content' => $content ), 'id,modified' );

        $result['saved']    = true;
        $result['modified'] = isset( $saved['modified'] ) ? $saved['modified'] : '';

        





        do_action( 'easy_mcp_ai_post_blocks_saved', $post_id, $changes );

        return $result;
    }

    









    private function apply_op( array &$root, array $op, $i, array &$warnings ) {
        $type = isset( $op['op'] ) && is_string( $op['op'] ) ? $op['op'] : '';
        if ( ! in_array( $type, self::OPS, true ) ) {
            throw new \InvalidArgumentException(
                sprintf( 'ops[%d]: op must be one of %s.', $i, implode( ', ', self::OPS ) ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            );
        }

        $has_path = isset( $op['path'] ) && '' !== $op['path'];

        if ( 'insert' === $type ) {
            $at = isset( $op['at'] ) && is_string( $op['at'] ) && '' !== $op['at'] ? $op['at'] : 'after';
            if ( ! in_array( $at, self::AT, true ) ) {
                throw new \InvalidArgumentException(
                    sprintf( 'ops[%d]: at must be one of %s.', $i, implode( ', ', self::AT ) ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                );
            }
            $blocks = $this->resolve_op_blocks( $op, $i );
            if ( 'append' === $at || 'prepend' === $at ) {
                if ( $has_path ) {
                    throw new \InvalidArgumentException(
                        sprintf( 'ops[%d]: at=%s inserts into the root list and does not take a path; use before/after with a path to insert next to a block.', $i, $at ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                    );
                }
                $this->root_insert_end( $root, $blocks, 'prepend' === $at );
                return array(
                    'op'       => 'insert',
                    'at'       => $at,
                    'inserted' => $this->names_of( $blocks ),
                );
            }
            if ( ! $has_path ) {
                throw new \InvalidArgumentException( sprintf( 'ops[%d]: insert with at=%s requires a path.', $i, $at ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            }
            $segments   = $this->parse_block_path( $op['path'] );
            $path_label = implode( '.', $segments );
            $container  = &$this->resolve_container( $root, $segments, $path_label );
            $raw        = $this->raw_index_at( $container['innerBlocks'], end( $segments ), $path_label, count( $segments ) - 1 );
            $anchor     = $this->block_display_name( $container['innerBlocks'][ $raw ] );
            $this->container_insert_relative( $container, $raw, $blocks, 'before' === $at );
            return array(
                'op'       => 'insert',
                'at'       => $at,
                'path'     => $path_label,
                'block'    => $anchor,
                'inserted' => $this->names_of( $blocks ),
            );
        }

        if ( ! $has_path ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: %s requires a path.', $i, $type ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }
        $segments   = $this->parse_block_path( $op['path'] );
        $path_label = implode( '.', $segments );
        $container  = &$this->resolve_container( $root, $segments, $path_label );
        $raw        = $this->raw_index_at( $container['innerBlocks'], end( $segments ), $path_label, count( $segments ) - 1 );
        $name       = $this->block_display_name( $container['innerBlocks'][ $raw ] );

        if ( 'remove' === $type ) {
            $this->container_remove( $container, $raw );
            return array( 'op' => 'remove', 'path' => $path_label, 'block' => $name );
        }

        if ( 'replace' === $type ) {
            $blocks = $this->resolve_op_blocks( $op, $i );
            $this->container_replace( $container, $raw, $blocks );
            return array(
                'op'       => 'replace',
                'path'     => $path_label,
                'block'    => $name,
                'inserted' => $this->names_of( $blocks ),
            );
        }

        
        $target = &$container['innerBlocks'][ $raw ];
        if ( empty( $target['blockName'] ) ) {
            throw new \InvalidArgumentException(
                sprintf( 'ops[%d]: the block at path "%s" is classic HTML and has no attributes; use replace.', $i, $path_label ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            );
        }
        if ( ! $this->is_block_type_registered( $name ) ) {
            throw new \InvalidArgumentException(
                sprintf( 'ops[%d]: block type %s at path "%s" is not registered on this server, so its attributes cannot be validated. A block registered only in the editor JavaScript cannot be edited with set_attributes; use replace.', $i, $name, $path_label ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            );
        }
        if ( ! isset( $op['attrs'] ) ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: set_attributes requires attrs.', $i ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }
        $attrs = $this->parse_json_param( $op['attrs'], sprintf( 'ops[%d].attrs', $i ) );
        if ( array() === $attrs ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: attrs must contain at least one key.', $i ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }
        if ( array_keys( $attrs ) === range( 0, count( $attrs ) - 1 ) ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: attrs must be an object of attribute name => value, not a list.', $i ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }

        $schema     = $this->block_attribute_schema( $name );
        $has_markup = $this->block_has_saved_markup( $target );
        $force      = ! empty( $op['force'] ) && rest_sanitize_boolean( $op['force'] );
        if ( ! isset( $target['attrs'] ) || ! is_array( $target['attrs'] ) ) {
            $target['attrs'] = array();
        }
        $set     = array();
        $deleted = array();
        $forced  = array();
        foreach ( $attrs as $key => $value ) {
            $key = (string) $key;
            if ( ! array_key_exists( $key, $schema ) ) {
                $declared = array_keys( $schema );
                throw new \InvalidArgumentException(
                    sprintf(
                        'ops[%d]: attribute "%s" is not declared by block type %s. Declared attributes: %s.',
                        $i,
                        $key, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        $name, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        empty( $declared ) ? '(none)' : implode( ', ', $declared ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                    )
                );
            }
            $decl  = is_array( $schema[ $key ] ) ? $schema[ $key ] : array();
            $types = isset( $decl['type'] ) ? $decl['type'] : null;
            if ( null !== $value && ! $this->attribute_type_matches( $value, $types ) ) {
                throw new \InvalidArgumentException(
                    sprintf(
                        'ops[%d]: attribute "%s" of %s expects type %s, got %s.',
                        $i,
                        $key, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        $name, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        implode( '|', (array) $types ), // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        $this->json_type_label( $value ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                    )
                );
            }
            
            
            
            
            
            
            if ( $has_markup && ! in_array( $key, self::DELIMITER_ONLY_ATTRIBUTES, true ) ) {
                if ( ! $force ) {
                    throw new \InvalidArgumentException(
                        sprintf(
                            'ops[%d]: %s at path "%s" has editor-generated HTML, so changing "%s" in the delimiter alone would leave the block invalid in the editor ("Block contains unexpected or invalid content. Attempt recovery"). Use replace with the full new block markup (read it with wp_get_post_blocks or wp_get_post and edit it), or pass force: true to write the delimiter anyway. Only metadata and lock can be set on such a block without force; a block whose saved form is empty (e.g. <!-- wp:latest-posts /-->) is rendered from its attributes and takes them freely.',
                            $i,
                            $name, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                            $path_label, // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                            $key // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
                        )
                    );
                }
                $forced[] = $key;
            } elseif ( ! $has_markup && null !== $value && ! empty( $decl['source'] ) ) {
                $warnings[] = sprintf(
                    'ops[%d]: attribute "%s" of %s is sourced from the block HTML (source: %s); set_attributes changed only the delimiter JSON, which the editor ignores for this attribute. Use replace with new markup to change it.',
                    $i,
                    $key,
                    $name,
                    (string) $decl['source']
                );
            }
            if ( null === $value ) {
                unset( $target['attrs'][ $key ] );
                $deleted[] = $key;
                continue;
            }
            $target['attrs'][ $key ] = $value;
            $set[]                   = $key;
        }

        if ( ! empty( $forced ) ) {
            $warnings[] = sprintf(
                'ops[%d]: force applied %s to %s at path "%s", which has editor-generated HTML; the editor will flag this block as invalid ("Attempt recovery") until it is recovered there, because its saved HTML no longer matches its attributes.',
                $i,
                implode( ', ', $forced ),
                $name,
                $path_label
            );
        }

        return array(
            'op'      => 'set_attributes',
            'path'    => $path_label,
            'block'   => $name,
            'set'     => $set,
            'deleted' => $deleted,
            'forced'  => $forced,
        );
    }

    







    private function resolve_op_blocks( array $op, $i ) {
        $has_content = isset( $op['content'] ) && is_string( $op['content'] ) && '' !== trim( $op['content'] );
        $has_pattern = isset( $op['pattern_slug'] ) && is_string( $op['pattern_slug'] ) && '' !== trim( $op['pattern_slug'] );

        if ( $has_content && $has_pattern ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: give either content or pattern_slug, not both.', $i ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }
        if ( ! $has_content && ! $has_pattern ) {
            throw new \InvalidArgumentException( sprintf( 'ops[%d]: %s requires content (block markup) or pattern_slug.', $i, $op['op'] ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
        }

        if ( $has_content ) {
            return $this->parse_markup_for_insert( $op['content'], sprintf( 'ops[%d].content', $i ) );
        }

        $slug = trim( $op['pattern_slug'] );
        if ( ! class_exists( 'WP_Block_Patterns_Registry' ) ) {
            throw new \RuntimeException( 'Block patterns are not available on this WordPress install.' );
        }
        $pattern = \WP_Block_Patterns_Registry::get_instance()->get_registered( $slug );
        if ( ! is_array( $pattern ) || ! isset( $pattern['content'] ) || ! is_string( $pattern['content'] ) ) {
            throw new \InvalidArgumentException(
                sprintf( 'ops[%d]: pattern "%s" is not registered on this site.', $i, $slug ) // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
            );
        }
        return $this->parse_markup_for_insert( $pattern['content'], sprintf( 'ops[%d]: pattern "%s"', $i, $slug ) );
    }

    





    private function names_of( array $blocks ) {
        $names = array();
        foreach ( $blocks as $block ) {
            $names[] = $this->block_display_name( $block );
        }
        return $names;
    }
