class Update_Post_Blocks extends Base_Tool {

    use Block_Tree;

    const OPS = array( 'set_attributes', 'replace', 'insert', 'remove' );
    const AT  = array( 'before', 'after', 'append', 'prepend' );

    
    const DELIMITER_ONLY_ATTRIBUTES = array( 'metadata', 'lock' );

    public function get_name() {
        return 'wp_update_post_blocks';
    }

    public function get_description() {
        return 'Edits individual Gutenberg blocks inside a post, page or custom post type item without rewriting the whole content. Read the tree with `wp_get_post_blocks` first to get paths. Required: `post_id`, `ops` (array of operations, applied in order). Optional: `post_type` (REST base, default `posts`), `dry_run` (validate and report without saving). Each op: `op` = `set_attributes` (merge `attrs` into the block\'s delimiter attributes; a null value deletes a key; only the comment JSON changes. On a block that has saved HTML between its delimiters — most core blocks: heading, paragraph, image, group, buttons — that HTML was generated by the editor from those attributes, so changing any attribute other than `metadata` or `lock` this way leaves the block invalid in the editor (a server render_callback does not change that: core/heading has one and is still validated); such ops are refused unless `force: true`, and the right tool is `replace` with the full edited markup. A block whose saved form is empty (self-closing, e.g. `<!-- wp:latest-posts /-->`, `<!-- wp:query /-->`, most Otter blocks) is rendered from its attributes and accepts any declared one), `replace` (swap the block at `path` for the blocks in `content` markup or a registered `pattern_slug`), `insert` (add the blocks from `content`/`pattern_slug`; `at` = `before`|`after` a `path` (default `after`), or `append`|`prepend` to the root list with no `path`), `remove` (delete the block at `path` with its children). Paths are dot-joined zero-based indexes (`0.2.1`) counting addressable blocks only, and every op addresses the tree AS IT IS after the previous ops (an insert shifts later siblings by one). Before anything is saved every block name in new markup must be registered on the server, `set_attributes` keys must exist in the block type\'s attribute schema with matching types, and a pattern must use only registered blocks — otherwise the call fails and the post is untouched. Saves through the same REST route as `wp_update_post`, so `edit_post`, content filtering and revisions apply. Returns { post_id, saved, ops_applied, block_count, warnings, changes }. This is not the synced-pattern tool: to edit a reusable block (wp_block post) use `wp_update_block`.';
    }

